@app.post("/api/recipes")
@logged_in
def recipes():
    if not GROQ_API_KEY:
        return jsonify({
            "configured": False,
            "message": "Add your Groq API key in Vercel as GROQ_API_KEY to turn on AI recipes."
        }), 503

    with connect() as db:
        items = db.execute(
            """
            SELECT name, quantity, unit
            FROM pantry_items
            WHERE user_id = %s
            ORDER BY name
            """,
            (session["user_id"],)
        ).fetchall()

    if not items:
        return jsonify({
            "error": "Add a few ingredients to your pantry first."
        }), 400

    ingredient_text = ", ".join(
        f"{item['quantity']} {item['unit']} {item['name']}"
        for item in items
    )

    try:
        response = requests.post(
            "https://api.groq.com/openai/v1/chat/completions",
            headers={
                "Authorization": f"Bearer {GROQ_API_KEY}",
                "Content-Type": "application/json"
            },
            json={
                "model": GROQ_MODEL,
                "temperature": 0.5,
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            'You are a practical cooking assistant. '
                            'Return valid JSON only in this shape: '
                            '{"recipes":[{"name":"...","time":"...",'
                            '"description":"...","ingredients":["..."],'
                            '"steps":["..."],"missing":["..."]}]}. '
                            'Suggest up to 3 safe, realistic recipes.'
                        )
                    },
                    {
                        "role": "user",
                        "content": (
                            "Make up to 3 recipe ideas using these "
                            f"ingredients: {ingredient_text}. "
                            "Prioritize available ingredients and list "
                            "any missing items."
                        )
                    }
                ]
            },
            timeout=35
        )

        response.raise_for_status()
        content = response.json()["choices"][0]["message"]["content"].strip()

        content = re.sub(
            r"^```(?:json)?\s*|\s*```$",
            "",
            content,
            flags=re.I
        )

        result = json.loads(content)

        if not isinstance(result.get("recipes"), list):
            raise ValueError("Unexpected recipe format")

        return jsonify({
            "configured": True,
            "recipes": result["recipes"]
        })

    except (
        requests.RequestException,
        KeyError,
        ValueError,
        TypeError
    ):
        app.logger.exception("Groq recipe call failed")
        return jsonify({
            "error": "The AI recipe service failed. Check your API key/model and try again."
        }), 502


