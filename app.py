@app.get("/api/pantry")
@logged_in
def get_pantry():
    with connect() as db:
        rows = db.execute(
            """
            SELECT id, barcode, name, brand, quantity, unit,
                   category, image_url, created_at
            FROM pantry_items
            WHERE user_id = %s
            ORDER BY name
            """,
            (session["user_id"],)
        ).fetchall()

    return jsonify(rows)


@app.post("/api/pantry")
@logged_in
def add_pantry():
    data = request.get_json(silent=True) or {}
    name = str(data.get("name", "")).strip()

    if not name or len(name) > 120:
        return jsonify({
            "error": "Enter a food name (up to 120 characters)."
        }), 400

    try:
        quantity = float(data.get("quantity", 1))
    except (ValueError, TypeError):
        return jsonify({"error": "Quantity must be a number."}), 400

    if not 0 < quantity <= 100000:
        return jsonify({
            "error": "Quantity must be greater than zero."
        }), 400

    values = (
        session["user_id"],
        str(data.get("barcode", ""))[:40],
        name,
        str(data.get("brand", ""))[:120],
        quantity,
        str(data.get("unit", "item"))[:24] or "item",
        str(data.get("category", ""))[:80],
        str(data.get("image_url", ""))[:500]
    )

    with connect() as db:
        row = db.execute(
            """
            INSERT INTO pantry_items
                (user_id, barcode, name, brand, quantity,
                 unit, category, image_url)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id, barcode, name, brand, quantity,
                      unit, category, image_url, created_at
            """,
            values
        ).fetchone()

    return jsonify(row), 201


@app.patch("/api/pantry/<int:item_id>")
@logged_in
def update_pantry(item_id):
    data = request.get_json(silent=True) or {}

    try:
        quantity = float(data.get("quantity"))
    except (ValueError, TypeError):
        return jsonify({"error": "Quantity must be a number."}), 400

    if quantity < 0 or quantity > 100000:
        return jsonify({
            "error": "Quantity must be between 0 and 100000."
        }), 400

    with connect() as db:
        existing = db.execute(
            """
            SELECT id FROM pantry_items
            WHERE id = %s AND user_id = %s
            """,
            (item_id, session["user_id"])
        ).fetchone()

        if not existing:
            return jsonify({"error": "Item not found."}), 404

        if quantity == 0:
            db.execute(
                """
                DELETE FROM pantry_items
                WHERE id = %s AND user_id = %s
                """,
                (item_id, session["user_id"])
            )
            return jsonify({"deleted": True})

        row = db.execute(
            """
            UPDATE pantry_items
            SET quantity = %s
            WHERE id = %s AND user_id = %s
            RETURNING id, barcode, name, brand, quantity,
                      unit, category, image_url, created_at
            """,
            (quantity, item_id, session["user_id"])
        ).fetchone()

    return jsonify(row)


@app.delete("/api/pantry/<int:item_id>")
@logged_in
def delete_pantry(item_id):
    with connect() as db:
        result = db.execute(
            """
            DELETE FROM pantry_items
            WHERE id = %s AND user_id = %s
            """,
            (item_id, session["user_id"])
        )

    if result.rowcount:
        return jsonify({"ok": True})

    return jsonify({"error": "Item not found."}), 404


