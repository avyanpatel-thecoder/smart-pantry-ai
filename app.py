@app.get("/api/barcode/<path:barcode>")
@logged_in
def barcode(barcode):
    barcode = re.sub(r"\D", "", barcode)

    if not 8 <= len(barcode) <= 14:
        return jsonify({
            "error": "That barcode number doesn't look valid."
        }), 400

    try:
        response = requests.get(
            f"https://world.openfoodfacts.org/api/v2/product/{barcode}.json",
            headers={"User-Agent": "SmartPantryAI/1.0"},
            timeout=8
        )
        response.raise_for_status()
        data = response.json()

    except (requests.RequestException, ValueError):
        return jsonify({
            "error": "Product lookup is temporarily unavailable. Add the food manually."
        }), 502

    product = data.get("product") or {}

    name = (
        product.get("product_name")
        or product.get("product_name_en")
        or product.get("generic_name")
        or ""
    ).strip()

    if data.get("status") != 1 or not name:
        return jsonify({
            "found": False,
            "barcode": barcode,
            "message": "Product not found. Add its name manually."
        })

    categories = product.get("categories_tags") or []

    return jsonify({
        "found": True,
        "barcode": barcode,
        "name": name[:120],
        "brand": (product.get("brands") or "")[:120],
        "category": (
            categories[0].replace("en:", "").replace("-", " ")[:80]
            if categories else ""
        ),
        "image_url": (
            product.get("image_front_small_url")
            or product.get("image_url")
            or ""
        )[:500]
    })


